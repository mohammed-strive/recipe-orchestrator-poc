// AGENT_RUNNER=stub: deterministic placeholder output for agent steps, so the whole
// pipeline can be exercised without an AI model (no cost, no network). Not for real use.
import { readFileSync } from "node:fs";
import { isFileValue } from "./util.js";

function load(v: unknown): unknown {
  if (isFileValue(v)) {
    try {
      return JSON.parse(readFileSync(v, "utf8"));
    } catch {
      return null;
    }
  }
  return v;
}

function describeTable(name: string, rows: Record<string, unknown>[]): string {
  const numeric = Object.keys(rows[0] ?? {}).find((k) => typeof rows[0][k] === "number");
  if (!numeric) return `${name}: ${rows.length} rows`;
  const values = rows.map((r) => Number(r[numeric]));
  return `${name}: ${rows.length} rows, ${numeric} from ${Math.min(...values).toLocaleString("en-US")} to ${Math.max(...values).toLocaleString("en-US")}`;
}

export function stubOutput(contract: string, task: string, inputs: Record<string, unknown>): unknown {
  const data = Object.fromEntries(Object.entries(inputs).map(([k, v]) => [k, load(v)]));
  if (contract === "doc/commentary@1") {
    const highlights = Object.entries(data)
      .filter(([, v]) => Array.isArray(v) && v.length)
      .map(([k, v]) => describeTable(k, v as Record<string, unknown>[]));
    return {
      title: `Stub commentary: ${task}`.slice(0, 120),
      highlights: highlights.length ? highlights : ["No tabular inputs were provided."],
      risks: ["Generated by the stub runner without an AI model; numbers are summarised, not interpreted."],
      narrative: `This placeholder commentary was produced by the stub agent runner for the task "${task}". ` +
        "Switch AGENT_RUNNER to claude to have a headless Claude Code session run the plugin's skill instead.",
    };
  }
  if (contract === "doc/report@1") {
    const c = (data.commentary ?? {}) as { title?: string; highlights?: string[]; risks?: string[]; narrative?: string };
    const title = c.title ?? "Report";
    const table = Array.isArray(data.table) ? (data.table as Record<string, unknown>[]).slice(0, 15) : [];
    const cols = Object.keys(table[0] ?? {});
    const md = [
      `# ${title}`, "", "## Summary", "", c.narrative ?? "", "", "## Highlights", "",
      ...(c.highlights ?? []).map((h) => `- ${h}`), "", "## Risks", "", ...(c.risks ?? []).map((r) => `- ${r}`), "",
      ...(cols.length
        ? ["## Supporting data", "", `| ${cols.join(" | ")} |`, `| ${cols.map(() => "---").join(" | ")} |`,
           ...table.map((row) => `| ${cols.map((k) => String(row[k])).join(" | ")} |`), ""]
        : []),
      "_Generated by the recipe engine POC (stub runner)._",
    ].join("\n");
    return { title, markdown: md };
  }
  throw new Error(`stub runner cannot produce ${contract}`);
}

// Hybrid retrieval: hard filters, then semantic (pgvector) and keyword (Postgres full text)
// recall, fused with reciprocal rank fusion. Final ranking by an LLM happens in the engine.
import { pool } from "./db.js";
import { embed, toPgVector } from "./embed.js";
import { isPreApproved, preApprovedSet } from "./policy.js";

export interface SearchFilters {
  query: string;
  kinds?: string[];
  tags?: string[];
  host?: string;
  available_contracts?: string[];
  required_outputs?: string[];
  plugin?: string;
  include_all_versions?: boolean;
  limit?: number;
}

export interface Candidate {
  component_id: string;
  plugin: string;
  version: string;
  sha: string;
  component: string;
  kind: string;
  summary: string;
  card_status: string;
  pre_approved: boolean;
  input_contracts: string[];
  output_contracts: string[];
  scores: { semantic: number | null; keyword: number | null; fused: number };
}

const RRF_K = 60;
// Cards generated by AI and not yet verified by the plugin owner rank lower.
const GENERATED_CARD_WEIGHT = Number(process.env.GENERATED_CARD_WEIGHT ?? 0.9);

function tsQuery(q: string): string | null {
  const words = [...new Set((q.toLowerCase().match(/[a-z0-9]+/g) ?? []).filter((w) => w.length > 2))];
  return words.length ? words.join(" | ") : null;
}

export async function search(f: SearchFilters): Promise<Candidate[]> {
  const [qvec] = await embed([f.query], "query");
  const where: string[] = [];
  const params: unknown[] = [toPgVector(qvec)];
  const add = (sql: string, value: unknown) => {
    params.push(value);
    where.push(sql.replace("?", `$${params.length}`));
  };
  if (!f.include_all_versions) where.push("is_latest");
  if (f.plugin) add("plugin = ?", f.plugin);
  if (f.kinds?.length) add("kind = any(?)", f.kinds);
  if (f.tags?.length) add("tags && ?", f.tags);
  if (f.host) add("? = any(hosts)", f.host);
  if (f.required_outputs?.length) add("output_contracts @> ?", f.required_outputs);
  if (f.available_contracts) add("input_contracts <@ ?", f.available_contracts);
  const tsq = tsQuery(f.query);
  params.push(tsq ?? "");
  const tsqParam = `$${params.length}`;
  params.push(Math.min(Math.max(f.limit ?? 10, 1), 50));
  const limitParam = `$${params.length}`;

  const sql = `
    with filtered as (
      select * from components ${where.length ? `where ${where.join(" and ")}` : ""}
    ),
    vec as (
      select id, 1 - (embedding <=> $1::vector) as sim,
             row_number() over (order by embedding <=> $1::vector) as r
      from filtered order by embedding <=> $1::vector limit 50
    ),
    txt as (
      select id, ts_rank(tsv, q) as rank, row_number() over (order by ts_rank(tsv, q) desc) as r
      from filtered, to_tsquery('english', ${tsqParam}) q
      where ${tsq ? "tsv @@ q" : "false"}
      order by rank desc limit 50
    )
    select f.id, f.plugin, f.version, f.sha, f.component, f.kind, f.summary, f.card_status,
           f.input_contracts, f.output_contracts, vec.sim, txt.rank as text_rank,
           (coalesce(1.0 / (${RRF_K} + vec.r), 0) + coalesce(1.0 / (${RRF_K} + txt.r), 0))
             * (case when f.card_status = 'verified' then 1.0 else ${GENERATED_CARD_WEIGHT} end) as fused
    from filtered f
    left join vec on vec.id = f.id
    left join txt on txt.id = f.id
    where vec.id is not null or txt.id is not null
    order by fused desc, f.id
    limit ${limitParam}`;
  const rows = (await pool.query(sql, params)).rows;
  const policy = preApprovedSet();
  return rows.map((r) => ({
    component_id: r.id,
    plugin: r.plugin,
    version: r.version,
    sha: r.sha,
    component: r.component,
    kind: r.kind,
    summary: r.summary,
    card_status: r.card_status,
    pre_approved: isPreApproved(policy, r.plugin, r.component, r.card_status),
    input_contracts: r.input_contracts,
    output_contracts: r.output_contracts,
    scores: {
      semantic: r.sim === null ? null : Number(Number(r.sim).toFixed(4)),
      keyword: r.text_rank === null ? null : Number(Number(r.text_rank).toFixed(4)),
      fused: Number(Number(r.fused).toFixed(5)),
    },
  }));
}

export async function getCard(componentId: string) {
  // Accepts plugin@version#component, or plugin#component for the latest version.
  const m = componentId.match(/^([^@#]+)(?:@([^#]+))?#(.+)$/);
  if (!m) throw new Error("component_id must look like plugin@version#component or plugin#component");
  const [, plugin, version, component] = m;
  const { rows } = version
    ? await pool.query("select * from components where plugin=$1 and version=$2 and component=$3", [plugin, version, component])
    : await pool.query("select * from components where plugin=$1 and component=$2 and is_latest", [plugin, component]);
  if (!rows.length) throw new Error(`No component ${componentId}`);
  const r = rows[0];
  return {
    component_id: r.id, plugin: r.plugin, version: r.version, sha: r.sha, card: r.card, card_status: r.card_status,
    pre_approved: isPreApproved(preApprovedSet(), r.plugin, r.component, r.card_status),
  };
}
